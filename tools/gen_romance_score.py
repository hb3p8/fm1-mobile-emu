#!/usr/bin/env python3
"""Compile the user's three MIDI parts into fixed-size C99 score tables.

No MIDI player, files, allocation or sample bank is needed on the instrument.
The two-bar lead-in and two-bar ending are excluded to loop the 128-bar take.
Starts/gates are rounded to the engine's 24 PPQN clock (max error 1/48 beat).
"""
import hashlib
import pathlib
import struct
import sys


def read_notes(data):
    assert data[:4] == b'MThd'
    size, = struct.unpack_from('>I', data, 4)
    fmt, count, ppqn = struct.unpack_from('>HHH', data, 8)
    assert fmt == 1 and not ppqn & 0x8000
    pos, tracks = 8 + size, []
    for _ in range(count):
        assert data[pos:pos + 4] == b'MTrk'
        size, = struct.unpack_from('>I', data, pos + 4)
        raw = data[pos + 8:pos + 8 + size]
        pos += 8 + size
        i, tick, status, active, notes = 0, 0, None, {}, []
        def vlq():
            nonlocal i
            value = 0
            while True:
                b = raw[i]
                i += 1
                value = (value << 7) | (b & 127)
                if b < 128:
                    return value
        while i < len(raw):
            tick += vlq()
            event = raw[i]
            if event >= 128:
                i += 1
                if event < 0xf0:
                    status = event
            else:
                assert status is not None
                event = status
            if event == 0xff:
                i += 1
                size = vlq()
                i += size
            elif event in (0xf0, 0xf7):
                size = vlq()
                i += size
            else:
                kind, channel = event >> 4, event & 15
                size = 1 if kind in (12, 13) else 2
                args = raw[i:i + size]
                i += size
                key = channel, args[0]
                if kind == 9 and args[1]:
                    active.setdefault(key, []).append((tick, args[1]))
                elif kind == 8 or kind == 9 and not args[1]:
                    assert active.get(key), ('unmatched note off', key, tick)
                    start, velocity = active[key].pop(0)
                    notes.append((start, tick, args[0], velocity))
        assert not any(active.values())
        tracks.append(sorted(notes))
    return ppqn, tracks


# Analytical chord chart, not a transcription of the muted string track's
# voicings. Roots are relative to B. Duration is in quarter notes.
# Scale indices agree with J_SCALE in jazz.inc.
CHART = [
    (0,0x291,4,0),(9,0x489,4,7),(7,0x495,4,2),(3,0x249,4,5),
    (4,0x489,4,8),(9,0x489,4,7),(2,0x48d,4,1),(7,0x491,4,2),
    (0,0x291,4,0),(4,0x489,2,8),(3,0x249,2,5),
    (2,0x48d,2,1),(7,0x495,2,2),(2,0x489,2,1),(7,0x491,2,2),
    (0,0x891,4,0),(4,0x489,2,8),(5,0x495,2,3),
    (4,0x511,2,6),(9,0x593,2,4),(2,0x489,2,1),(7,0x495,2,2),
    (0,0x291,4,0),(9,0x489,4,7),(7,0x495,4,2),(3,0x249,4,5),
    (4,0x489,4,8),(9,0x489,4,7),(2,0x489,4,1),(7,0x491,4,2),
    (0,0x291,4,0),(7,0x489,2,1),(0,0x491,2,2),(5,0x891,4,0),
    (6,0x249,2,5),(5,0x495,2,3),(4,0x489,2,8),(9,0x489,2,7),
    (2,0x489,2,1),(7,0x491,2,2),(0,0x291,4,0),(2,0x489,2,1),(7,0x491,2,2),
]


def main():
    source = pathlib.Path(__file__).resolve().parents[1] / 'assets/scores/a_fine_romance_mw.mid'
    data = source.read_bytes()
    ppqn, tracks = read_notes(data)
    assert len(tracks) == 20 and [len(tracks[i]) for i in (6,7,11)] == [464,1199,1348]
    def quant(t):
        return (t * 24 + ppqn // 2) // ppqn
    events, counts = [], []
    for track, part in ((6,2),(7,4),(11,0)):
        count = 0
        for start, end, note, velocity in tracks[track]:
            if 8 * ppqn <= start < 520 * ppqn:
                at = quant(start - 8 * ppqn)
                gate = max(1, quant(end - start))
                assert 0 <= at < 128 * 96 and gate < 65536
                events.append((at, gate, note, velocity, part))
                count += 1
        counts.append(count)
    events.sort(key=lambda e: (e[0], e[4], e[2]))
    assert set(e[2] for e in events if e[4] == 0) <= {35,37,38,42,46,49,51}
    text = ['/* Generated by tools/gen_romance_score.py; do not edit.',
            ' * Musical data: user-supplied A Fine Romance, MIDI arrangement by Mel Webb.',
            ' * No open-source licence is asserted for the musical arrangement.',
            ' * Source SHA256: ' + hashlib.sha256(data).hexdigest() + ' */',
            '#pragma once', '#define ROMANCE_TICKS (128u * 96u)',
            '#define ROMANCE_COUNT %du' % len(events),
            'typedef struct { uint16_t at, gate; uint8_t note, velocity, part; } romance_note_t;',
            'static const romance_note_t ROMANCE_NOTES[ROMANCE_COUNT] = {']
    text += ['    {%d,%d,%d,%d,%d},' % e for e in events]
    text += ['};', 'typedef struct { uint16_t at, mask; uint8_t root, beats, scale; } romance_chord_t;',
             '#define ROMANCE_CHORDS %du' % len(CHART),
             'static const romance_chord_t ROMANCE_HARMONY[ROMANCE_CHORDS] = {']
    at = 0
    for root, mask, beats, scale in CHART:
        text.append('    {%d,0x%03x,%d,%d,%d},' % (at,mask,root,beats,scale))
        at += beats * 24
    assert at == 32 * 96
    text += ['};', '']
    target = pathlib.Path(sys.argv[1])
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(text))
    from gen_romance_forms import write_forms
    write_forms(events,CHART,target.with_name('romance_forms.h'))
    print('%s: %d notes (bass %d, piano %d, drums %d), %d chords, 128 bars' % (target,len(events),*counts,len(CHART)))


if __name__ == '__main__':
    main()
